async function pool(items, limit, fn) {
  let cursor = 0;
  const workers = Array.from({ length: Math.min(limit, items.length) }, async () => {
    for (;;) {
      const i = cursor++;
      if (i >= items.length) return;
      await fn(items[i], i);
    }
  });
  await Promise.all(workers);
}

async function volumeOf(file) {
  const err = await new Promise((resolve, reject) => {
    const child = spawn("ffmpeg", ["-hide_banner", "-i", file, "-af", "volumedetect", "-f", "null", "-"], { stdio: ["ignore", "ignore", "pipe"] });
    let text = "";
    child.stderr.on("data", (d) => {
      text += d;
    });
    child.on("close", (code) => (code === 0 ? resolve(text) : reject(new Error(text.slice(-300)))));
  });
  const mean = err.match(/mean_volume:\s*(-?[\d.]+) dB/)?.[1];
  const max = err.match(/max_volume:\s*(-?[\d.]+) dB/)?.[1];
  return `${path.basename(file)} mean ${mean} dB max ${max} dB`;
}

