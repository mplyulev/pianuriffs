function run(cmd, args) {
  return new Promise((resolve, reject) => {
    const child = spawn(cmd, args, { stdio: ["ignore", "pipe", "pipe"] });
    let out = "";
    let err = "";
    child.stdout.on("data", (d) => {
      out += d;
    });
    child.stderr.on("data", (d) => {
      err += d;
    });
    child.on("close", (code) => {
      if (code === 0) resolve(out.trim());
      else reject(new Error(`${cmd} ${args.join(" ")} failed: ${err.slice(-500)}`));
    });
  });
}

async function durationOf(file) {
  const out = await run("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file]);
  const n = Number(out);
  if (!Number.isFinite(n) || n <= 0) throw new Error(`bad duration for ${file}: ${out}`);
  return n;
}

async function isOgg(file) {
  try {
    const info = await stat(file);
    if (info.size < 800) return false;
    const buf = await readFile(file);
    return buf.subarray(0, 4).toString() === "OggS";
  } catch {
    return false;
  }
}

async function download(url, dest) {
  let last = "download failed";
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      const res = await fetch(url);
      if (res.status === 429 || res.status >= 500) throw new Error(`HTTP ${res.status}`);
      if (!res.ok) throw new Error(`HTTP ${res.status} ${url}`);
      const buf = Buffer.from(await res.arrayBuffer());
      if (buf.length < 1000 || buf.subarray(0, 4).toString() !== "fLaC") {
        throw new Error(`not a flac (${buf.length} bytes) ${url}`);
      }
      await writeFile(dest, buf);
      return;
    } catch (err) {
      last = err instanceof Error ? err.message : String(err);
      await new Promise((r) => setTimeout(r, 500 * (attempt + 1) * (attempt + 1)));
    }
  }
  throw new Error(`${url}: ${last}`);
}

async function encode(job) {
  if (await isOgg(job.out)) return "skip";
  await mkdir(path.dirname(job.out), { recursive: true });
  const rel = path.relative(OUT, job.out);
  const flac = path.join(RAW, `${rel}.flac`);
  const part = path.join(RAW, `${rel}.tmp.ogg`);
  await mkdir(path.dirname(flac), { recursive: true });
  let haveFlac = false;
  try {
    const buf = await readFile(flac);
    haveFlac = buf.length > 1000 && buf.subarray(0, 4).toString() === "fLaC";
  } catch {
    haveFlac = false;
  }
  if (!haveFlac) await download(job.url, flac);
  const src = await durationOf(flac);
  const dur = Math.max(0.12, Math.min(job.cap, src - 0.01));
  const fade = Math.min(job.fade, dur * 0.35);
  const start = Math.max(0, dur - fade);
  await run("ffmpeg", [
    "-y",
    "-hide_banner",
    "-loglevel",
    "error",
    "-i",
    flac,
    "-t",
    dur.toFixed(3),
    "-ac",
    "1",
    "-ar",
    "48000",
    "-af",
    `afade=t=out:st=${start.toFixed(3)}:d=${fade.toFixed(3)}`,
    "-c:a",
    "libvorbis",
    "-q:a",
    String(job.q),
    "-map_metadata",
    "-1",
    "-f",
    "ogg",
    part,
  ]);
  if (!(await isOgg(part))) throw new Error(`encode produced no ogg for ${job.out}`);
  await rename(part, job.out);
  await rm(flac, { force: true });
  return "ok";
}

function jobs() {
  const list = [];
  for (const layer of LAYERS) {
    for (const zone of PIANO) {
      const remote = `${zone.stem}${layer.id}.flac`;
      list.push({
        url: `https://raw.githubusercontent.com/sfzinstruments/SalamanderGrandPiano/master/Samples/${encodeURIComponent(remote)}`,
        out: path.join(OUT, "piano", `${safe(zone.stem)}${layer.id}.ogg`),
        cap: pianoCap(zone.root),
        fade: 0.4,
        q: 4,
      });
    }
  }
  for (let n = 1; n <= 88; n++) {
    list.push({
      url: `https://raw.githubusercontent.com/sfzinstruments/SalamanderGrandPiano/master/Samples/rel${n}.flac`,
      out: path.join(OUT, "piano", `rel${n}.ogg`),
      cap: 1.2,
      fade: 0.06,
      q: 2,
    });
  }
  for (const zone of FINGER) {
    list.push({
      url: `https://raw.githubusercontent.com/freepats/electric-bass-YR/main/samples/finger/${encodeURIComponent(`${zone.file}.flac`)}`,
      out: path.join(OUT, "bass/finger", `${safe(zone.file)}.ogg`),
      cap: 8,
      fade: 0.08,
      q: 5,
    });
  }
  for (const zone of PICK) {
    list.push({
      url: `https://raw.githubusercontent.com/freepats/electric-bass-YR/main/samples/pick/${encodeURIComponent(`${zone.file}.flac`)}`,
      out: path.join(OUT, "bass/pick", `${safe(zone.file)}.ogg`),
      cap: 8,
      fade: 0.08,
      q: 5,
    });
  }
  return list;
}

async function pool(items, limit, fn) {
  let cursor = 0;
  const workers = Array.from({ length: Math.min(limit, items.length) }, async () => {
    for (;;) {
      const i = cursor++;
      if (i >= items.length) return;
      await fn(items[i], i);
    }
  });
  await Promise.all(workers);
}

async function volumeOf(file) {
  const err = await new Promise((resolve, reject) => {
    const child = spawn("ffmpeg", ["-hide_banner", "-i", file, "-af", "volumedetect", "-f", "null", "-"], { stdio: ["ignore", "ignore", "pipe"] });
    let text = "";
    child.stderr.on("data", (d) => {
      text += d;
    });
    child.on("close", (code) => (code === 0 ? resolve(text) : reject(new Error(text.slice(-300)))));
  });
  const mean = err.match(/mean_volume:\s*(-?[\d.]+) dB/)?.[1];
  const max = err.match(/max_volume:\s*(-?[\d.]+) dB/)?.[1];
  return `${path.basename(file)} mean ${mean} dB max ${max} dB`;
}

