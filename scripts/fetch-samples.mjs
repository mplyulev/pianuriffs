function run(cmd, args) {
  return new Promise((resolve, reject) => {
    const child = spawn(cmd, args, { stdio: ["ignore", "pipe", "pipe"] });
    let out = "";
    let err = "";
    child.stdout.on("data", (d) => {
      out += d;
    });
    child.stderr.on("data", (d) => {
      err += d;
    });
    child.on("close", (code) => {
      if (code === 0) resolve(out.trim());
      else reject(new Error(`${cmd} ${args.join(" ")} failed: ${err.slice(-500)}`));
    });
  });
}

async function durationOf(file) {
  const out = await run("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file]);
  const n = Number(out);
  if (!Number.isFinite(n) || n <= 0) throw new Error(`bad duration for ${file}: ${out}`);
  return n;
}

async function isOgg(file) {
  try {
    const info = await stat(file);
    if (info.size < 800) return false;
    const buf = await readFile(file);
    return buf.subarray(0, 4).toString() === "OggS";
  } catch {
    return false;
  }
}

async function download(url, dest) {
  let last = "download failed";
  for (let attempt = 0; attempt < 5; attempt++) {
    try {
      const res = await fetch(url);
      if (res.status === 429 || res.status >= 500) throw new Error(`HTTP ${res.status}`);
      if (!res.ok) throw new Error(`HTTP ${res.status} ${url}`);
      const buf = Buffer.from(await res.arrayBuffer());
      const magic = buf.subarray(0, 4).toString();
      if (buf.length < 1000 || (magic !== "fLaC" && magic !== "RIFF")) {
        throw new Error(`not audio (${buf.length} bytes, ${magic}) ${url}`);
      }
      await writeFile(dest, buf);
      return;
    } catch (err) {
      last = err instanceof Error ? err.message : String(err);
      await new Promise((r) => setTimeout(r, 500 * (attempt + 1) * (attempt + 1)));
    }
  }
  throw new Error(`${url}: ${last}`);
}

async function encode(job) {
  if (await isOgg(job.out)) return "skip";
  await mkdir(path.dirname(job.out), { recursive: true });
  const rel = path.relative(OUT, job.out);
  const flac = path.join(RAW, `${rel}.flac`);
  const part = path.join(RAW, `${rel}.tmp.ogg`);
  await mkdir(path.dirname(flac), { recursive: true });
  let haveFlac = false;
  try {
    const buf = await readFile(flac);
    const magic = buf.subarray(0, 4).toString();
    haveFlac = buf.length > 1000 && (magic === "fLaC" || magic === "RIFF");
  } catch {
    haveFlac = false;
  }
  if (!haveFlac) await download(job.url, flac);
  const src = await durationOf(flac);
  const looped = (job.loopEnd ?? 0) > 0.05;
  let dur = Math.min(job.cap, src);
  if (!looped) dur = Math.max(0.12, Math.min(dur, src - 0.01));
  if (looped) dur = Math.min(src, Math.max(dur, Math.min(src, job.loopEnd + 0.03)));
  const fade = !looped && job.fade > 0 ? Math.min(job.fade, dur * 0.35) : 0;
  const start = Math.max(0, dur - fade);
  const trim = !looped && dur < src - 0.02;
  const args = ["-y", "-hide_banner", "-loglevel", "error", "-i", flac];
  if (trim) args.push("-t", dur.toFixed(3));
  args.push("-ac", "1", "-ar", "48000");
  if (fade > 0) args.push("-af", `afade=t=out:st=${start.toFixed(3)}:d=${fade.toFixed(3)}`);
  args.push("-c:a", "libvorbis", "-q:a", String(job.q), "-map_metadata", "-1", "-f", "ogg", part);
  await run("ffmpeg", args);
  if (!(await isOgg(part))) throw new Error(`encode produced no ogg for ${job.out}`);
  await rename(part, job.out);
  await rm(flac, { force: true });
  return "ok";
}

