function emitProgram(program) {
  const zones = program.zones
    .map((zone) => {
      const layers = zone.layers
        .map((layer) => {
          const loop =
            layer.loopEnd > layer.loopStart
              ? `, loopStart: ${Number(layer.loopStart.toFixed(5))}, loopEnd: ${Number(layer.loopEnd.toFixed(5))}`
              : "";
          return `      { lo: ${layer.lo}, hi: ${layer.hi}, file: "${layer.file}", offset: 0${loop} },`;
        })
        .join("\n");
      return `    { root: ${zone.root}, lo: ${zone.lo}, hi: ${zone.hi}, release: ${zone.release}, layers: [\n${layers}\n    ] },`;
    })
    .join("\n");
  return `  ${program.id}: {
    id: "${program.id}",
    gain: ${program.gain},
    velTrack: ${program.velTrack},
    credit: ${JSON.stringify(program.credit)},
    releases: [],
    zones: [
${zones}
    ],
  },`;
}

/** One opcode, or several `key=value` pairs on a single SFZ line. Values may contain spaces when they are the only opcode. */
function opcodes(line) {
  if (/^[A-Za-z0-9_]+=/.test(line) && !/\s[A-Za-z0-9_]+=/.test(line)) {
    const eq = line.indexOf("=");
    return [[line.slice(0, eq).trim().toLowerCase(), line.slice(eq + 1).trim()]];
  }
  const found = [];
  const re = /([A-Za-z0-9_]+)=("[^"]*"|[^\s]+)/g;
  let match;
  while ((match = re.exec(line))) found.push([match[1].toLowerCase(), match[2].replace(/^"|"$/g, "")]);
  return found;
}

function parseSfz(text) {
  const cur = {
    release: 0.4,
    lovel: 0,
    hivel: 127,
    lokey: null,
    hikey: null,
    root: null,
    loopStart: null,
    loopEnd: null,
    sample: "",
    path: "",
  };
  const regions = [];
  let inRegion = false;
  const flush = () => {
    if (inRegion && cur.sample) regions.push({ ...cur });
    inRegion = false;
  };
  const apply = (key, val) => {
    if (key === "default_path") cur.path = val.replaceAll("\\", "/");
    else if (key === "ampeg_release") cur.release = Number(val);
    else if (key === "sample") cur.sample = val.replaceAll("\\", "/");
    else if (key === "lokey") cur.lokey = Number(val);
    else if (key === "hikey") cur.hikey = Number(val);
    else if (key === "pitch_keycenter") cur.root = Number(val);
    else if (key === "key") cur.lokey = cur.hikey = cur.root = Number(val);
    else if (key === "lovel") cur.lovel = Number(val);
    else if (key === "hivel") cur.hivel = Number(val);
    else if (key === "loop_start") cur.loopStart = Number(val);
    else if (key === "loop_end") cur.loopEnd = Number(val);
  };
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.replace(/\/\/.*$/, "").trim();
    if (!line) continue;
    if (line.startsWith("<")) {
      flush();
      const tag = line.slice(1).split(/[\s>]/)[0].toLowerCase();
      inRegion = tag === "region";
      if (tag === "global") {
        cur.lovel = 0;
        cur.hivel = 127;
        cur.loopStart = null;
        cur.loopEnd = null;
      }
      if (inRegion) {
        cur.sample = "";
        cur.loopStart = null;
        cur.loopEnd = null;
      }
      const rest = line.replace(/^<[^>]*>/, "").trim();
      if (rest) for (const [key, val] of opcodes(rest)) apply(key, val);
      continue;
    }
    for (const [key, val] of opcodes(line)) apply(key, val);
  }
  flush();
  return regions.filter(
    (region) => region.sample && Number.isFinite(region.root) && Number.isFinite(region.lokey) && Number.isFinite(region.hikey),
  );
}

function urlJoin(base, filePath) {
  const parts = filePath.split("/").filter(Boolean).map(encodeURIComponent);
  return `${base.replace(/\/$/, "")}/${parts.join("/")}`;
}

function buildProgram(spec, regions) {
  const grouped = new Map();
  for (const region of regions) {
    const key = `${region.root}:${region.lokey}:${region.hikey}`;
    if (!grouped.has(key)) {
      grouped.set(key, {
        root: region.root,
        lo: region.lokey,
        hi: region.hikey,
        release: region.release,
        layers: [],
      });
    }
    const baseName = region.sample.split("/").pop();
    const file = `samples/${spec.dir}/${spec.prefix ? `${spec.prefix}_` : ""}${safe(baseName).replace(/\.wav$|\.flac$/i, "")}.ogg`;
    const remote = urlJoin(spec.base, `${region.path}${region.sample}`.replace(/\/{2,}/g, "/"));
    grouped.get(key).layers.push({
      lo: Math.max(1, region.lovel || 1),
      hi: region.hivel || 127,
      file,
      offset: 0,
      loopStart: region.loopEnd ? region.loopStart / spec.rate : 0,
      loopEnd: region.loopEnd ? region.loopEnd / spec.rate : 0,
      url: remote,
      cap: spec.cap,
      fade: spec.fade,
      q: spec.q,
    });
  }
  const zones = [...grouped.values()].sort((a, b) => a.lo - b.lo || a.root - b.root);
  for (const zone of zones) zone.layers.sort((a, b) => a.lo - b.lo);
  return {
    id: spec.id,
    gain: spec.gain,
    velTrack: spec.velTrack,
    credit: spec.credit,
    zones,
  };
}

