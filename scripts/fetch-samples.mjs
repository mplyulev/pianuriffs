const safe = (name) => name.replaceAll("#", "s");
const sec = (samples) => (samples / 48000).toFixed(6).replace(/0+$/, "").replace(/\.$/, ".0");

function pianoRelease(root) {
  return root >= 90 ? 1.7 : 0.48;
}

function pianoCap(root) {
  if (root < 40) return 12;
  if (root < 60) return 9;
  if (root < 80) return 5;
  return 3.5;
}

